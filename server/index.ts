import { makeServer } from './http.js';
import { createCollector } from './collector.js';
import { createWorkspaceRepository } from './workspace.js';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const collect = createCollector();
const workspace = createWorkspaceRepository();
const server = makeServer(collect, resolve(fileURLToPath(new URL('../../dist/', import.meta.url))), workspace);
server.requestTimeout = 15_000; server.headersTimeout = 10_000;
server.listen(8790, '127.0.0.1', () => { console.log('Shrinkcage → http://localhost:8790'); void collect().catch(() => {}); void workspace.get().catch(() => {}); });
server.on('error', error => { console.error(`Could not start Shrinkcage: ${(error as NodeJS.ErrnoException).code ?? 'server error'}. Check whether port 8790 is already in use.`); process.exitCode = 1; });
for (const signal of ['SIGINT', 'SIGTERM'] as const) process.on(signal, () => { server.close(() => process.exit(0)); server.closeIdleConnections(); });
